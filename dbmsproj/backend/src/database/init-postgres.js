import fs from 'fs';
import path from 'path';
import pg from 'pg';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const connectionString = 'postgresql://neondb_owner:npg_Weo6v1uPaLyK@ep-cold-wind-ap3kkg8c.c-7.us-east-1.aws.neon.tech/neondb?sslmode=require';

async function init() {
  console.log('Connecting to Neon PostgreSQL...');
  const client = new pg.Client({
    connectionString,
    ssl: { rejectUnauthorized: false }
  });
  
  await client.connect();
  console.log('Connected!');

  try {
    const schemaPath = path.join(__dirname, '../../../schema.sql');
    let schemaSql = fs.readFileSync(schemaPath, 'utf8');

    console.log('Translating schema SQL from MS SQL Server syntax to Postgres...');
    
    // Remove drops and check idents
    schemaSql = schemaSql
      .replace(/IF OBJECT_ID\([\s\S]+?DROP TABLE[\s\S]+?;/gi, '')
      .replace(/DROP TABLE IF EXISTS \w+;/gi, '')
      .replace(/DBCC CHECKIDENT[\s\S]+?;/gi, '');

    // Convert basic MS SQL Server schemas to standard PostgreSQL
    schemaSql = schemaSql
      .replace(/IDENTITY\(1,1\)/gi, 'GENERATED BY DEFAULT AS IDENTITY')
      .replace(/DATETIME/gi, 'TIMESTAMP')
      .replace(/VARCHAR\((MAX|max)\)/gi, 'TEXT')
      .replace(/NVARCHAR/gi, 'VARCHAR')
      .replace(/MONEY/gi, 'DECIMAL(10,2)')
      .replace(/GO\b/gi, ';')
      .replace(/UNIQUEIDENTIFIER/gi, 'UUID')
      .replace(/NEWID\(\)/gi, 'gen_random_uuid()')
      .replace(/PRIMARY KEY\s+CLUSTERED/gi, 'PRIMARY KEY')
      .replace(/CONSTRAINT\s+\[\w+\]\s+FOREIGN KEY/gi, 'FOREIGN KEY');

    // Split into individual statements
    const statements = schemaSql
      .split(';')
      .map(s => s.trim())
      .filter(s => s.length > 0 && !s.startsWith('--') && !s.startsWith('USE'));

    console.log(`Executing ${statements.length} schema queries on Postgres...`);
    for (const stmt of statements) {
      try {
        await client.query(stmt);
      } catch (err) {
        if (!stmt.includes('DROP') && !stmt.includes('ALTER')) {
          console.warn('Query warning/error:', err.message);
        }
      }
    }
    console.log('PostgreSQL Schema Applied successfully!');

  } catch (err) {
    console.error('Initialization error:', err);
  } finally {
    await client.end();
  }
}

init();
