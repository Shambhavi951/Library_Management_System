CREATE TABLE membership_plans (
    membership_plan_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_name VARCHAR(30) UNIQUE NOT NULL,
    monthly_cost DECIMAL(10,2),
    max_active_borrows INT,
    reservation_limit INT,
    hold_duration_hours INT,
    queue_priority INT,
    cross_branch_priority CHAR(1),
    reading_list_limit INT
);

